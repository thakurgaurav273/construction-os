'use client';

import React, { useState } from 'react';
import { isAxiosError } from 'axios';
import { Button, Card, CardContent, CardHeader, CardTitle, Skeleton } from '@sitepilot/ui';
import { RefreshCw, Sparkles } from 'lucide-react';
import { useCan } from '@/hooks/api/use-access';
import { useAiStatus, useSummarizeDailyReport } from '@/hooks/api/use-ai';
import { getApiErrorMessage } from '@/lib/api/errors';
import { SafeMarkdown } from './SafeMarkdown';
import { AiUnavailableNotice } from './AiUnavailableNotice';

interface DailyReportAiSummaryProps {
  projectId: string;
  reportId: string;
  summary: string | null;
}

/** The report's saved AI summary, and a button to create or refresh it. Everyone sees the same saved summary. */
export function DailyReportAiSummary({ projectId, reportId, summary }: DailyReportAiSummaryProps): React.ReactElement | null {
  const canUse = useCan()('ai.use');
  const { data: status } = useAiStatus();
  const summarize = useSummarizeDailyReport();
  const [error, setError] = useState<string | null>(null);
  if (!summary && !canUse) return null;

  async function generate(): Promise<void> {
    setError(null);
    try {
      await summarize.mutateAsync({ projectId, reportId });
    } catch (failure) {
      const message = isAxiosError<{ message?: string }>(failure) && failure.response?.status === 403
        ? failure.response.data?.message ?? null
        : null;
      setError(message ?? getApiErrorMessage(failure, 'Couldn’t summarise the report. Try again.'));
    }
  }

  const unavailable = status?.mode === 'NONE' ? status.blockedReason : null;

  return (
    <Card className="border-indigo-200 dark:border-indigo-800/60">
      <CardHeader className="flex flex-row items-center justify-between gap-2 space-y-0 border-b bg-indigo-50/50 dark:bg-indigo-950/20">
        <CardTitle className="flex items-center gap-2 text-base text-indigo-700 dark:text-indigo-400">
          <Sparkles className="h-4 w-4" /> AI Summary
        </CardTitle>
        {canUse && !unavailable && (
          <Button size="sm" variant={summary ? 'ghost' : 'default'} disabled={summarize.isPending} onClick={() => { void generate(); }}>
            {summary ? <><RefreshCw className="mr-1.5 h-3.5 w-3.5" /> Regenerate</> : <><Sparkles className="mr-1.5 h-3.5 w-3.5" /> Summarise with AI</>}
          </Button>
        )}
      </CardHeader>
      <CardContent className="space-y-3 p-6">
        {summarize.isPending ? (
          <div className="space-y-2"><Skeleton className="h-4 w-full" /><Skeleton className="h-4 w-5/6" /><Skeleton className="h-4 w-2/3" /></div>
        ) : summary ? (
          <SafeMarkdown content={summary} />
        ) : unavailable ? (
          <AiUnavailableNotice reason={unavailable} compact />
        ) : (
          <p className="text-sm text-muted-foreground">Get a short summary of work done, issues and next steps from this report.</p>
        )}
        {error && <p className="text-sm text-destructive" role="alert">{error}</p>}
        {summary && !summarize.isPending && <p className="text-[11px] text-muted-foreground">Generated by AI from this report. Check important details against the report itself.</p>}
      </CardContent>
    </Card>
  );
}
