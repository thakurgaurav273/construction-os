'use client';

import React, { useState } from 'react';
import { toast } from 'sonner';
import { formatDistanceToNow } from 'date-fns';
import { AlertTriangle, CalendarClock, ChevronLeft, ChevronRight, Eye, FileText, Loader2, Trash2 } from 'lucide-react';
import {
  Badge, Button, Card, CardContent, CardDescription, CardHeader, CardTitle, Dialog, DialogContent, DialogDescription,
  DialogFooter, DialogHeader, DialogTitle, Skeleton,
} from '@sitepilot/ui';
import { Can } from '@/components/shared/Can';
import { EmptyState } from '@/components/shared/EmptyState';
import { useDeleteReport, useReportHistory } from '@/hooks/api/use-reports';
import { getApiErrorMessage } from '@/lib/api/errors';
import { FORMAT_LABELS, STATUS_PRESENTATION, TYPE_LABELS, formatFileSize, formatPeriod, isInProgress } from '../report-presentation';
import type { GeneratedReport } from '../types';
import { ReportDownloadButtons } from './ReportDownloadButtons';

const PAGE_SIZE = 20;

interface ReportHistoryListProps {
  onPreview: (report: GeneratedReport) => void;
  onBrowseTemplates: () => void;
}

function ReportRow({ report, onPreview, onDelete }: { report: GeneratedReport; onPreview: () => void; onDelete: () => void }): React.ReactElement {
  const status = STATUS_PRESENTATION[report.status];
  return (
    <li className="flex flex-col gap-3 p-4 lg:flex-row lg:items-center lg:justify-between">
      <div className="flex min-w-0 items-start gap-3">
        <FileText className="mt-0.5 h-5 w-5 shrink-0 text-muted-foreground" />
        <div className="min-w-0 space-y-1">
          <div className="flex flex-wrap items-center gap-2">
            <p className="truncate font-medium">{report.name}</p>
            <Badge variant={status.variant}>
              {isInProgress(report.status) && <Loader2 className="mr-1 h-3 w-3 animate-spin" />}
              {status.label}
            </Badge>
            {report.scheduleId && <Badge variant="outline"><CalendarClock className="mr-1 h-3 w-3" /> Scheduled</Badge>}
          </div>
          <p className="text-sm text-muted-foreground">
            {TYPE_LABELS[report.type]} · {formatPeriod(report.periodFrom, report.periodTo)} · {FORMAT_LABELS[report.format]}
            {report.status === 'COMPLETED' && ` · ${formatFileSize(report.fileSize)}`}
            {' · '}{formatDistanceToNow(new Date(report.generatedAt), { addSuffix: true })}
          </p>
          {report.status === 'FAILED' && report.error && <p className="text-sm text-destructive">{report.error}</p>}
        </div>
      </div>
      <div className="flex shrink-0 flex-wrap items-center gap-2">
        {report.status === 'COMPLETED' && (
          <Button variant="ghost" size="sm" onClick={onPreview}><Eye className="mr-1.5 h-4 w-4" /> Preview</Button>
        )}
        <ReportDownloadButtons report={report} />
        <Can permission="report.manage">
          <Button variant="ghost" size="icon" className="text-destructive hover:text-destructive/90" aria-label={`Delete ${report.name}`} onClick={onDelete}>
            <Trash2 className="h-4 w-4" />
          </Button>
        </Can>
      </div>
    </li>
  );
}

export function ReportHistoryList({ onPreview, onBrowseTemplates }: ReportHistoryListProps): React.ReactElement {
  const [page, setPage] = useState(1);
  const [deleting, setDeleting] = useState<GeneratedReport | null>(null);
  const { data, isLoading, isError, refetch } = useReportHistory(page, PAGE_SIZE);
  const deleteReport = useDeleteReport();
  const totalPages = data ? Math.max(1, Math.ceil(data.total / PAGE_SIZE)) : 1;

  async function handleDelete(): Promise<void> {
    if (!deleting) return;
    try {
      await deleteReport.mutateAsync(deleting.id);
      toast.success(`Deleted “${deleting.name}”`);
      setDeleting(null);
    } catch (error) {
      toast.error(getApiErrorMessage(error, 'Couldn’t delete the report. Try again.'));
    }
  }

  if (isLoading) return <div className="space-y-2">{Array.from({ length: 5 }).map((_, index) => <Skeleton key={index} className="h-20 w-full rounded-lg" />)}</div>;
  if (isError || !data) {
    return (
      <EmptyState
        icon={AlertTriangle}
        title="Unable to load generated reports"
        description="Check your connection and try again."
        action={<Button variant="outline" onClick={() => refetch()}>Retry</Button>}
      />
    );
  }
  if (data.total === 0) {
    return (
      <EmptyState
        icon={FileText}
        title="No reports yet"
        description="Generate a report from a template. Finished reports are kept here to preview and download."
        action={<Button onClick={onBrowseTemplates}>Browse templates</Button>}
      />
    );
  }

  return (
    <Card>
      <CardHeader>
        <CardTitle>Generated reports</CardTitle>
        <CardDescription>Reports generated by your team and by schedules. Files stay available to download.</CardDescription>
      </CardHeader>
      <CardContent>
        <ul className="divide-y rounded-lg border">
          {data.items.map((report) => (
            <ReportRow key={report.id} report={report} onPreview={() => onPreview(report)} onDelete={() => setDeleting(report)} />
          ))}
        </ul>
        {totalPages > 1 && (
          <div className="mt-4 flex items-center justify-between text-sm text-muted-foreground">
            <span>{data.total.toLocaleString('en-IN')} reports</span>
            <div className="flex items-center gap-2">
              <Button variant="outline" size="icon" className="h-8 w-8" aria-label="Previous page" disabled={page <= 1} onClick={() => setPage(page - 1)}>
                <ChevronLeft className="h-4 w-4" />
              </Button>
              <span>Page {page} of {totalPages}</span>
              <Button variant="outline" size="icon" className="h-8 w-8" aria-label="Next page" disabled={page >= totalPages} onClick={() => setPage(page + 1)}>
                <ChevronRight className="h-4 w-4" />
              </Button>
            </div>
          </div>
        )}
      </CardContent>

      <Dialog open={deleting !== null} onOpenChange={(open) => { if (!open) setDeleting(null); }}>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>Delete this report?</DialogTitle>
            <DialogDescription>“{deleting?.name}” and its files will be removed. Links already emailed will stop working.</DialogDescription>
          </DialogHeader>
          <DialogFooter>
            <Button variant="outline" onClick={() => setDeleting(null)}>Cancel</Button>
            <Button variant="destructive" loading={deleteReport.isPending} onClick={() => { void handleDelete(); }}>Delete report</Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </Card>
  );
}
