/** Contrast maths shared by validation; the frontend has a matching copy for live feedback. */
export const HEX_COLOR = /^#[0-9a-fA-F]{6}$/;

/** Links, icons and focus rings in the brand colour must stand out on white (WCAG 3:1 for UI components). */
export const MIN_BRAND_CONTRAST = 3;

function channel(value: number): number {
  const scaled = value / 255;
  return scaled <= 0.03928 ? scaled / 12.92 : ((scaled + 0.055) / 1.055) ** 2.4;
}

export function relativeLuminance(hex: string): number {
  const [r, g, b] = [1, 3, 5].map((start) => parseInt(hex.slice(start, start + 2), 16));
  return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
}

export function contrastRatio(a: string, b: string): number {
  const [light, dark] = [relativeLuminance(a), relativeLuminance(b)].sort((x, y) => y - x);
  return (light + 0.05) / (dark + 0.05);
}
